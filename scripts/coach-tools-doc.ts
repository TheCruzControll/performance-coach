/**
 * The coach's tools catalogue, generated from the registry so the docs cannot drift from it:
 *
 *   pnpm docs:coach-tools
 *
 * It writes two things from COACH_TOOLS (src/lib/server/agent/tools/registry.ts) and
 * TOOL_CATALOGUE (src/lib/domain/coach/tools.ts):
 * - docs/coach-tools.md, the whole file: one section per tool, in the order requests list them,
 *   with its group, effect and whether it drafts, the description the model reads, its strict
 *   input JSON Schema exactly as sent (fields, types, required keys, and the bounds strict mode
 *   lacks, moved into descriptions) and its output JSON Schema.
 * - the index table between the generated markers in docs/agent-architecture.md, one row per
 *   tool linking to its section. Everything outside the markers is hand-written.
 *
 * A schema is printed as a nested field list, one line per field: every keyword the strict
 * converter keeps (schema.ts) has a place in it, and any other keyword throws, so nothing in a
 * schema can be left out of the docs. scripts/coach-tools-doc.test.ts fails when either file is
 * stale.
 *
 * The registry imports the services, whose extensionless imports plain node cannot resolve, so
 * `pnpm docs:coach-tools` runs the test file in write mode (COACH_TOOLS_DOC=write) through Vitest.
 */
import { format, resolveConfig } from 'prettier';
import { fileURLToPath } from 'node:url';
import { TOOL_GROUP_LABEL } from '../src/lib/domain/coach/tools.ts';
import type { CoachTool } from '../src/lib/server/agent/tools/define.ts';
import { toStrictJsonSchema, type JsonSchema } from '../src/lib/server/agent/tools/schema.ts';

export const TOOLS_DOC = 'docs/coach-tools.md';
export const ARCHITECTURE_DOC = 'docs/agent-architecture.md';
export const BEGIN_MARKER = '<!-- coach-tools:begin (generated by `pnpm docs:coach-tools`) -->';
export const END_MARKER = '<!-- coach-tools:end -->';

/** A repository-relative path, resolved from this script (whatever the working directory). */
export const absolute = (file: string) => fileURLToPath(new URL(`../${file}`, import.meta.url));

/** The keywords a strict tool schema can hold (schema.ts); anything else is refused here. */
const KNOWN = new Set(
	'type properties required additionalProperties description title enum const anyOf allOf items minItems format'.split(
		' '
	)
);

const EFFECT_LABEL = {
	read: 'read: changes nothing',
	propose:
		'propose: stores a coach_proposals row, which changes nothing until the owner accepts it',
	write: 'write: one of the two direct writes'
};

/** Inline prose: one line, with nothing markdown would read as markup. */
const prose = (text: string) =>
	text
		.replace(/\s*\n\s*/g, ' ')
		.replace(/([\\`*_[\]<>|])/g, '\\$1')
		.trim();
const code = (text: string) => `\`${text}\``;
const literal = (value: unknown) => code(JSON.stringify(value));

function check(node: JsonSchema, at: string) {
	for (const key of Object.keys(node))
		if (!KNOWN.has(key)) throw new Error(`${at}: the catalogue cannot print '${key}'`);
	if ('additionalProperties' in node && node.additionalProperties !== false)
		throw new Error(`${at}: an open object is not a strict schema`);
}

const variants = (node: JsonSchema) => (node.anyOf ?? []) as JsonSchema[];
const parts = (node: JsonSchema) => (node.allOf ?? []) as JsonSchema[];
const isNull = (node: JsonSchema) => node.type === 'null' && Object.keys(node).length === 1;
/** The one other variant of a nullable node (`anyOf: [T, null]`), printed as T or null. */
const nullableOf = (node: JsonSchema): JsonSchema | undefined => {
	const real = variants(node).filter((v) => !isNull(v));
	return real.length === 1 && variants(node).length === 2 ? real[0] : undefined;
};

/** True when a node prints on one line: no fields, no nested variants, no description. */
function isLeaf(node: JsonSchema): boolean {
	if (node.type === 'object' || parts(node).length > 0 || node.description || node.title)
		return false;
	if (node.type === 'array') return isLeaf((node.items ?? {}) as JsonSchema);
	return variants(node).every(isLeaf);
}

/** A node's type in a few words: `string (date)`, `"a" | "b"`, `array of integer`. */
function typeLabel(node: JsonSchema, at: string): string {
	check(node, at);
	if (node.const !== undefined) return literal(node.const);
	if (Array.isArray(node.enum)) return node.enum.map(literal).join(' | ');
	const real = nullableOf(node);
	if (real) return `${typeLabel(real, `${at}.anyOf[0]`)} | null`;
	if (variants(node).length > 0 && variants(node).every(isLeaf))
		return variants(node)
			.map((v, i) => typeLabel(v, `${at}.anyOf[${i}]`))
			.join(' | ');
	if (variants(node).length > 0) return `one of ${variants(node).length}`;
	if (parts(node).length > 0) return `all of ${parts(node).length}`;
	const type = String(node.type);
	if (type === 'array') {
		const items = (node.items ?? {}) as JsonSchema;
		const min = node.minItems === 1 ? 'non-empty ' : '';
		return `${min}array of ${node.items ? typeLabel(items, `${at}[]`) : 'anything'}`;
	}
	if (type === 'object' && Object.keys((node.properties ?? {}) as JsonSchema).length === 0)
		return 'object with no fields';
	return node.format ? `${type} (${String(node.format)})` : type;
}

/** The lines under a node: its fields, an array's item fields, or its variants. */
function children(node: JsonSchema, at: string, depth: number): string[] {
	const pad = '  '.repeat(depth);
	const real = nullableOf(node);
	if (real) return children(real, `${at}.anyOf[0]`, depth);
	if (node.type === 'object') {
		const required = new Set((node.required ?? []) as string[]);
		return Object.entries((node.properties ?? {}) as Record<string, JsonSchema>).flatMap(
			([name, child]) => field(name, child, required.has(name), `${at}.${name}`, depth)
		);
	}
	if (node.type === 'array' && node.items) {
		const items = node.items as JsonSchema;
		return isLeaf(items) ? [] : children(items, `${at}[]`, depth);
	}
	const nested = [
		...variants(node).map((v, i) => ['anyOf', v, i] as const),
		...parts(node).map((p, i) => ['allOf', p, i] as const)
	];
	if (nested.length === 0 || (parts(node).length === 0 && variants(node).every(isLeaf))) return [];
	return nested.flatMap(([key, v, i]) => {
		const where = `${at}.${key}[${i}]`;
		const said = describe(v);
		return [
			`${pad}- ${key === 'anyOf' ? 'or' : 'and'} ${typeLabel(v, where)}${said}`,
			...children(v, where, depth + 1)
		];
	});
}

function describe(node: JsonSchema): string {
	const words = [node.title, node.description].filter((w): w is string => typeof w === 'string');
	return words.length ? `: ${prose(words.join('. '))}` : '';
}

function field(
	name: string,
	node: JsonSchema,
	required: boolean,
	at: string,
	depth: number
): string[] {
	const pad = '  '.repeat(depth);
	const label = `${typeLabel(node, at)}${required ? ', required' : ''}`;
	return [`${pad}- ${code(name)} (${label})${describe(node)}`, ...children(node, at, depth + 1)];
}

/**
 * A strict JSON Schema as a nested markdown field list: an object's fields, or for a union (some
 * outputs are one of several shapes) a line saying so and each variant's fields.
 */
export function schemaOutline(schema: JsonSchema, at = '$'): string {
	check(schema, at);
	const said = describe(schema);
	const lines = children(schema, at, 0);
	if (schema.type !== 'object')
		return [`The result is ${typeLabel(schema, at)}${said}`, '', ...lines].join('\n').trim();
	const head = said ? [`The object${said}`, ''] : [];
	return [...head, ...(lines.length ? lines : ['No fields.'])].join('\n');
}

export function toolSection(tool: CoachTool): string {
	const { name, entry, definition } = tool;
	return [
		`## ${name}`,
		'',
		`- **Group:** ${TOOL_GROUP_LABEL[entry.group]}`,
		`- **Effect:** ${EFFECT_LABEL[entry.effect]}`,
		`- **Drafts:** ${entry.drafts ? 'yes: a structured-output draft, so its deadline adds the draft time' : 'no'}`,
		'',
		prose(definition.description),
		'',
		'### Input',
		'',
		schemaOutline(definition.input_schema as JsonSchema, `${name}.input`),
		'',
		'### Output',
		'',
		schemaOutline(toStrictJsonSchema(tool.outputSchema, 'output'), `${name}.output`)
	].join('\n');
}

async function formatted(source: string, file: string): Promise<string> {
	const path = absolute(file);
	return format(source, { ...(await resolveConfig(path)), filepath: path });
}

/** docs/coach-tools.md, whole. */
export async function renderToolsDoc(tools: readonly CoachTool[]): Promise<string> {
	const source = [
		'# Coach tools',
		'',
		'Generated by `pnpm docs:coach-tools` from the registry (`src/lib/server/agent/tools/registry.ts`)',
		'and the catalogue (`src/lib/domain/coach/tools.ts`): do not edit this file by hand. How the',
		'tools fit the coach: [the agent architecture](agent-architecture.md#tools).',
		'',
		`The ${tools.length} tools, in the order every request lists them. Every input is strict: a closed`,
		'object whose required keys are marked, with each bound strict mode cannot state (lengths,',
		'ranges, patterns) written in braces in its description; zod still enforces every bound before',
		'the tool runs. A field without "required" may be left out. The output is what the tool',
		'returns as its tool result, before the 8 KB cap shortens a long page (`truncated`).',
		'',
		...tools.flatMap((tool) => [toolSection(tool), ''])
	].join('\n');
	return formatted(source, TOOLS_DOC);
}

/** The table between the markers in docs/agent-architecture.md. */
export function catalogueIndex(tools: readonly CoachTool[]): string {
	const rows = tools.map(({ name, entry }) =>
		[
			`[${code(name)}](coach-tools.md#${name})`,
			TOOL_GROUP_LABEL[entry.group],
			entry.effect,
			entry.drafts ? 'yes' : 'no'
		].join(' | ')
	);
	return [
		'| Tool | Group | Effect | Drafts |',
		'| --- | --- | --- | --- |',
		...rows.map((row) => `| ${row} |`)
	].join('\n');
}

/** `doc` with the text between its one pair of markers replaced by `generated`. */
export function spliceGenerated(doc: string, generated: string): string {
	const begin = doc.indexOf(BEGIN_MARKER);
	const end = doc.indexOf(END_MARKER);
	if (begin === -1 || end === -1 || end < begin)
		throw new Error(`${ARCHITECTURE_DOC} needs ${BEGIN_MARKER} … ${END_MARKER}, in that order`);
	if (doc.indexOf(BEGIN_MARKER, begin + 1) !== -1 || doc.indexOf(END_MARKER, end + 1) !== -1)
		throw new Error(`${ARCHITECTURE_DOC} has more than one pair of generated markers`);
	return `${doc.slice(0, begin + BEGIN_MARKER.length)}\n\n${generated}\n\n${doc.slice(end)}`;
}

/** docs/agent-architecture.md as `doc`, with a fresh index between its markers. */
export async function renderArchitecture(
	doc: string,
	tools: readonly CoachTool[]
): Promise<string> {
	return formatted(spliceGenerated(doc, catalogueIndex(tools)), ARCHITECTURE_DOC);
}
