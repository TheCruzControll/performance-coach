/**
 * Write docs/lifecycles.md from the lifecycle registry (src/lib/domain/lifecycles.ts):
 *
 *   pnpm lifecycles
 *
 * One section per lifecycle: where it is stored, its states (initial and terminal), the code
 * that writes it and the tests that pin it, then one table row per event and from-state. An edge
 * not proven from code shows as `unknown`; one allowed today but meant to go shows as legacy.
 * The file is committed, and scripts/lifecycles.test.ts fails when it is stale.
 */
import { writeFileSync } from 'node:fs';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { format, resolveConfig } from 'prettier';
import { lifecycleRows } from '../src/lib/domain/lifecycle.ts';
import type { Lifecycle } from '../src/lib/domain/lifecycle.ts';
import { LIFECYCLES } from '../src/lib/domain/lifecycles.ts';

export const LIFECYCLES_FILE = 'docs/lifecycles.md';

/** A repository-relative path, resolved from this script (whatever the working directory). */
const absolute = (file: string) => fileURLToPath(new URL(`../${file}`, import.meta.url));

/** A table cell: a pipe or a line break would end the cell. */
const cell = (text: string) => text.replace(/\|/g, '\\|').replace(/\s*\n\s*/g, ' ');
const code = (text: string) => `\`${text}\``;
const list = (items: readonly string[]) => (items.length ? items.map(code).join(', ') : 'none');

function section(l: Lifecycle<string, string>): string {
	const rows = lifecycleRows(l).map((row) =>
		[
			code(row.from),
			code(row.event),
			code(row.to),
			row.effects,
			row.certainty,
			row.legacy ? 'yes' : 'no',
			row.why
		]
			.map(cell)
			.join(' | ')
	);
	return [
		`## ${l.id}`,
		'',
		`- **Stored in:** ${l.storedIn}`,
		`- **States:** ${list(l.states)} (initial: ${list(l.initial)}; terminal: ${list(l.terminal)})`,
		`- **Write sites:** ${list(l.writeSites)}`,
		`- **Tests:** ${list(l.tests)}`,
		'',
		'| From | Event | To | Effects | Certainty | Legacy | Why |',
		'| --- | --- | --- | --- | --- | --- | --- |',
		...rows.map((row) => `| ${row} |`)
	].join('\n');
}

export async function renderLifecycles(
	list: readonly Lifecycle<string, string>[]
): Promise<string> {
	const file = absolute(LIFECYCLES_FILE);
	const source = [
		'# Lifecycles',
		'',
		'Generated by `pnpm lifecycles` from `src/lib/domain/lifecycles.ts`: do not edit this file by',
		'hand. Edit the table first, then run `pnpm lifecycles`. Each row is one event from one state.',
		'An edge marked `unknown` is not proven from code; a legacy edge is allowed today and meant to',
		'go. Why the tables exist: the "Lifecycles as data" ADR in `docs/adr/`.',
		'',
		...list.flatMap((l) => [section(l), ''])
	].join('\n');
	return format(source, { ...(await resolveConfig(file)), filepath: file });
}

async function main() {
	writeFileSync(absolute(LIFECYCLES_FILE), await renderLifecycles(LIFECYCLES));
	console.log(`lifecycles: wrote ${LIFECYCLES_FILE} (${LIFECYCLES.length} lifecycles)`);
}

if (import.meta.url === pathToFileURL(process.argv[1] ?? '').href) {
	await main();
}
